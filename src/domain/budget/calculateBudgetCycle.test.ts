import { describe, expect, it } from 'vitest';
import { calculateBudgetCycle } from './calculateBudgetCycle';
import type { DateOnly } from '../models';

describe('calculateBudgetCycle', () => {
  it.each<[DateOnly, number, DateOnly, DateOnly]>([
    ['2026-09-24', 25, '2026-08-25', '2026-09-25'],
    ['2026-09-25', 25, '2026-09-25', '2026-10-25'],
    ['2026-09-30', 25, '2026-09-25', '2026-10-25'],
    ['2026-10-01', 25, '2026-09-25', '2026-10-25'],
    ['2027-01-01', 25, '2026-12-25', '2027-01-25'],
    ['2026-12-31', 25, '2026-12-25', '2027-01-25'],
    ['2026-09-01', 1, '2026-09-01', '2026-10-01'],
    ['2026-04-29', 31, '2026-03-31', '2026-04-30'],
    ['2026-04-30', 31, '2026-04-30', '2026-05-31'],
    ['2026-05-01', 31, '2026-04-30', '2026-05-31'],
    ['2026-02-27', 29, '2026-01-29', '2026-02-28'],
    ['2026-02-28', 29, '2026-02-28', '2026-03-29'],
    ['2026-02-28', 30, '2026-02-28', '2026-03-30'],
    ['2026-02-28', 31, '2026-02-28', '2026-03-31'],
    ['2028-02-28', 29, '2028-01-29', '2028-02-29'],
    ['2028-02-29', 29, '2028-02-29', '2028-03-29'],
    ['2028-02-29', 30, '2028-02-29', '2028-03-30'],
    ['2028-02-29', 31, '2028-02-29', '2028-03-31'],
    ['2028-03-01', 31, '2028-02-29', '2028-03-31'],
    ['2026-12-31', 31, '2026-12-31', '2027-01-31'],
  ])('%s / 매월 %i일 → %s ~ %s', (today, payday, startedOn, nextPayday) => {
    expect(calculateBudgetCycle(today, payday)).toEqual({ today, startedOn, nextPayday });
  });
  it.each([0, 32, 1.5, NaN])('잘못된 월급일 %s를 거부한다', payday => {
    expect(() => calculateBudgetCycle('2026-09-30', payday)).toThrow(RangeError);
  });
  it('존재하지 않는 날짜를 거부한다', () => {
    expect(() => calculateBudgetCycle('2026-02-29', 25)).toThrow(RangeError);
  });
});
